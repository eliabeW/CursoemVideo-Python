a = 5
b = 2

print("Soma:", a + b)        # 5 + 2 = 7
print("Subtração:", a - b)   # 5 - 2 = 3
print("Multiplicação:", a * b)  # 5 * 2 = 10
print("Divisão:", a / b)     # 5 / 2 = 2.5

print("Potência:", a ** b)   # 5 ** 2 = 25
print("Divisão inteira:", a // b)  # 5 // 2 = 2
print("Resto:", a % b)       # 5 % 2 = 1
